-- CineDiary database schema (MySQL 5.7+/8.0, MariaDB 10.3+)
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS BinhLuanThich, BinhLuan, DanhSachPhim, DanhSachTuyChinh, DanhGia, Phim, NguoiDung;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE NguoiDung (
  maNguoiDung INT AUTO_INCREMENT PRIMARY KEY,
  tenDangNhap VARCHAR(100) NOT NULL UNIQUE,
  email VARCHAR(255) NOT NULL UNIQUE,
  matKhau VARCHAR(255) NOT NULL,
  anhDaiDien VARCHAR(255) NULL,
  tieuSu TEXT NULL,
  vaiTro VARCHAR(20) NOT NULL DEFAULT 'ThanhVien',   -- 'ThanhVien' | 'QuanTriVien'
  trangThai VARCHAR(20) NOT NULL DEFAULT 'active',   -- 'active' | 'locked'
  ngayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ngayCapNhat DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE Phim (
  maPhim INT AUTO_INCREMENT PRIMARY KEY,
  tenPhimVN VARCHAR(255) NOT NULL,
  tenPhimEN VARCHAR(255) NULL,
  namSanXuat INT NOT NULL,
  thoiLuong INT NOT NULL,
  theLoai VARCHAR(255) NOT NULL,
  daoDien VARCHAR(255) NOT NULL,
  dienVien TEXT NOT NULL,
  noiDung TEXT NOT NULL,
  giaVe INT UNSIGNED NOT NULL DEFAULT 0,
  duongDanTrailer VARCHAR(255) NULL,
  duongDanPoster VARCHAR(255) NULL,
  diemTrungBinh DECIMAL(3,1) NOT NULL DEFAULT 0,
  ngayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ngayCapNhat DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_phim_nam (namSanXuat)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE DanhGia (
  maDanhGia INT AUTO_INCREMENT PRIMARY KEY,
  maPhim INT NOT NULL,
  maNguoiDung INT NOT NULL,
  tieuDe VARCHAR(255) NOT NULL,
  noiDung TEXT NOT NULL,
  diemSo DECIMAL(2,1) NOT NULL,
  anhMinhHoa VARCHAR(255) NULL,
  trangThai ENUM('active','pending','hidden') NOT NULL DEFAULT 'active',
  ngayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ngayCapNhat DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_danhgia_phim (maPhim),
  CONSTRAINT fk_danhgia_phim FOREIGN KEY (maPhim) REFERENCES Phim(maPhim) ON DELETE CASCADE,
  CONSTRAINT fk_danhgia_nguoidung FOREIGN KEY (maNguoiDung) REFERENCES NguoiDung(maNguoiDung) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE BinhLuan (
  maBinhLuan INT AUTO_INCREMENT PRIMARY KEY,
  maDanhGia INT NULL,
  maPhim INT NULL,
  maNguoiDung INT NOT NULL,
  maBinhLuanCha INT NULL,
  noiDung TEXT NOT NULL,
  trangThai ENUM('active','pending','hidden') NOT NULL DEFAULT 'active',
  ngayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ngayCapNhat DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_binhluan_danhgia (maDanhGia),
  CONSTRAINT fk_binhluan_danhgia FOREIGN KEY (maDanhGia) REFERENCES DanhGia(maDanhGia) ON DELETE CASCADE,
  CONSTRAINT fk_binhluan_nguoidung FOREIGN KEY (maNguoiDung) REFERENCES NguoiDung(maNguoiDung) ON DELETE CASCADE,
  CONSTRAINT fk_binhluan_cha FOREIGN KEY (maBinhLuanCha) REFERENCES BinhLuan(maBinhLuan) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE BinhLuanThich (
  maBinhLuan INT NOT NULL,
  maNguoiDung INT NOT NULL,
  ngayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (maBinhLuan, maNguoiDung),
  CONSTRAINT fk_blt_binhluan FOREIGN KEY (maBinhLuan) REFERENCES BinhLuan(maBinhLuan) ON DELETE CASCADE,
  CONSTRAINT fk_blt_nguoidung FOREIGN KEY (maNguoiDung) REFERENCES NguoiDung(maNguoiDung) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE DanhSachTuyChinh (
  maDanhSach INT AUTO_INCREMENT PRIMARY KEY,
  maNguoiDung INT NOT NULL,
  tenDanhSach VARCHAR(255) NOT NULL,
  moTa TEXT NULL,
  congKhai TINYINT(1) NOT NULL DEFAULT 1,
  ngayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ngayCapNhat DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_danhsach_user (maNguoiDung),
  CONSTRAINT fk_danhsach_nguoidung FOREIGN KEY (maNguoiDung) REFERENCES NguoiDung(maNguoiDung) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE DanhSachPhim (
  maMuc INT AUTO_INCREMENT PRIMARY KEY,
  maDanhSach INT NOT NULL,
  maPhim INT NOT NULL,
  ghiChu TEXT NULL,
  thuTu INT NOT NULL DEFAULT 1,
  ngayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ngayCapNhat DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uniq_danhsach_phim (maDanhSach, maPhim),
  CONSTRAINT fk_dsp_danhsach FOREIGN KEY (maDanhSach) REFERENCES DanhSachTuyChinh(maDanhSach) ON DELETE CASCADE,
  CONSTRAINT fk_dsp_phim FOREIGN KEY (maPhim) REFERENCES Phim(maPhim) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
